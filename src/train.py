"""
Training module for the DSS150P reproduction pipeline.

Responsibilities:
- Read the curated parquet.
- Enforce a deterministic, reproducible train/test split.
- Write metadata/split_manifest.json with row counts, class distribution,
  and hashes so the split is provably the same across machines.
- Train the configured model (random forest by default) with fixed seed.
- Persist the model artifact to outputs/model/model.joblib.
- Return the fitted model and the test set for evaluation.

The training module never writes predictions or metrics; those are
produced by src/evaluate.py.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import logging
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any

import joblib
import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import train_test_split

from src.config import Settings, configure_logging, get_settings

log = logging.getLogger(__name__)


# ----------------------------------------------------------------------
# Feature selection
# ----------------------------------------------------------------------
CATEGORICAL_HINTS = {
    "collision_year", "day_of_week", "police_force", "first_road_class",
    "first_road_number", "road_type", "junction_detail", "junction_control",
    "pedestrian_crossing", "light_conditions", "weather_conditions",
    "road_surface_conditions", "special_conditions_at_site",
    "carriageway_hazards", "urban_or_rural_area",
    "did_police_officer_attend_scene_of_accident", "trunk_road_flag",
    "hour", "month", "year",
}

NUMERIC_HINTS = {
    "number_of_vehicles", "number_of_casualties", "speed_limit",
    "longitude", "latitude",
}

NEVER_FEATURES = {
    "collision_index", "collision_ref_no",
    "collision_severity", "is_fatal",
    "collision_date", "collision_time", "collision_datetime",
    "date", "time", "local_authority_ons_district",
    "local_authority_highway", "local_authority_highway_current",
    "lsoa_of_accident_location",
}


def select_features(df: pd.DataFrame) -> list[str]:
    candidates = [
        c for c in df.columns
        if c not in NEVER_FEATURES and (c in CATEGORICAL_HINTS or c in NUMERIC_HINTS)
    ]
    if not candidates:
        raise ValueError("No feature columns selected. Check the curated schema.")
    return candidates


# ----------------------------------------------------------------------
# Split manifest
# ----------------------------------------------------------------------
def _hash_indices(idx: pd.Index) -> str:
    h = hashlib.sha256()
    for v in idx:
        h.update(str(v).encode("utf-8"))
        h.update(b"\n")
    return h.hexdigest()


@dataclass
class SplitManifest:
    train_indices_sha256: str
    test_indices_sha256: str
    train_rows: int
    test_rows: int
    train_fatal_0: int
    train_fatal_1: int
    test_fatal_0: int
    test_fatal_1: int
    random_state: int
    test_size: float

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


def write_split_manifest(settings: Settings, manifest: SplitManifest) -> Path:
    path = settings.metadata_dir / "split_manifest.json"
    payload = {
        "_comment": "Auto-generated by src/train.py after each run. Values must remain stable unless the dataset checksum or split strategy changes.",
        "dataset": "uk_dft_stats19_collision",
        "dataset_checksum_sha256": settings.source_checksum,
        "strategy": {
            "method": "train_test_split",
            "library": "sklearn.model_selection",
            "stratify_on": "is_fatal",
            "shuffle": True,
            "random_state": manifest.random_state,
            "test_size": manifest.test_size,
            "train_size": 1 - manifest.test_size,
        },
        "row_counts": {
            "total": manifest.train_rows + manifest.test_rows,
            "train": manifest.train_rows,
            "test": manifest.test_rows,
        },
        "class_distribution": {
            "train": {"is_fatal_0": manifest.train_fatal_0, "is_fatal_1": manifest.train_fatal_1},
            "test": {"is_fatal_0": manifest.test_fatal_0, "is_fatal_1": manifest.test_fatal_1},
        },
        "hashes": {
            "train_indices_sha256": manifest.train_indices_sha256,
            "test_indices_sha256": manifest.test_indices_sha256,
        },
        "ordering": {
            "sort_key_before_split": ["collision_index"],
            "description": "Curated data is sorted by collision_index before splitting so that index assignment is deterministic regardless of upstream row order.",
        },
        "reproducibility": {
            "notes": "Hashes are stable across machines provided the curated parquet is identical and the seed is unchanged.",
        },
    }
    path.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    return path


# ----------------------------------------------------------------------
# Model selection
# ----------------------------------------------------------------------
def build_model(settings: Settings):
    algo = settings.algorithm.lower()
    hp = dict(settings.hyperparameters)
    seed = settings.random_seed

    if algo == "random_forest":
        return RandomForestClassifier(random_state=seed, n_jobs=-1, **hp)
    if algo == "logistic_regression":
        return LogisticRegression(random_state=seed, max_iter=1000, **hp)
    raise ValueError(f"Unsupported algorithm: {settings.algorithm}")


# ----------------------------------------------------------------------
# Training
# ----------------------------------------------------------------------
def train(settings: Settings | None = None) -> dict[str, Any]:
    s = settings or get_settings()
    s.model_dir.mkdir(parents=True, exist_ok=True)

    curated = pd.read_parquet(s.curated_dir / "curated.parquet")
    log.info("Loaded curated: %d rows, %d columns", len(curated), curated.shape[1])

    features = select_features(curated)
    log.info("Selected %d features: %s", len(features), features)

    X = curated[features].copy()
    y = curated["is_fatal"].astype(int)

    X_train, X_test, y_train, y_test = train_test_split(
        X, y,
        test_size=s.test_size,
        random_state=s.random_seed,
        stratify=y,
        shuffle=True,
    )

    manifest = SplitManifest(
        train_indices_sha256=_hash_indices(X_train.index),
        test_indices_sha256=_hash_indices(X_test.index),
        train_rows=len(X_train),
        test_rows=len(X_test),
        train_fatal_0=int((y_train == 0).sum()),
        train_fatal_1=int((y_train == 1).sum()),
        test_fatal_0=int((y_test == 0).sum()),
        test_fatal_1=int((y_test == 1).sum()),
        random_state=s.random_seed,
        test_size=s.test_size,
    )
    write_split_manifest(s, manifest)
    log.info("Split manifest written: train=%d test=%d", manifest.train_rows, manifest.test_rows)

    model = build_model(s)
    log.info("Training %s...", s.algorithm)
    model.fit(X_train, y_train)

    artifact = s.model_dir / "model.joblib"
    joblib.dump({"model": model, "features": features}, artifact)
    log.info("Model artifact saved: %s", artifact)

    return {
        "features": features,
        "train_rows": manifest.train_rows,
        "test_rows": manifest.test_rows,
        "artifact": str(artifact),
    }


# ----------------------------------------------------------------------
# CLI
# ----------------------------------------------------------------------
def _cli() -> None:
    parser = argparse.ArgumentParser(description="DSS150P train")
    parser.parse_args()

    s = get_settings()
    configure_logging(s)

    info = train(s)
    print(json.dumps(info, indent=2))


if __name__ == "__main__":
    _cli()